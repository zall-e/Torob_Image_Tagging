def manage_clusters(processor, entity_name):
    """
    Manages cluster operations based on user input.

    Args:
        processor (DictListProcessor): An instance of the DictListProcessor class.
    """
    result = processor.get_entity_clusters(entity_name)
    for ent in result.keys():
      print(ent)
      print(result[ent])

    print("Enter the action you want to perform:")
    print("1. Change cluster name")
    print("2. Swap value(s) between clusters")
    print("3. Merge clusters")
    print("4. Create a new cluster")
    print("Enter 'exit' to quit.")

    while True:
        choice = input("Enter your choice (1-4 or 'exit'): ").strip().lower()

        if choice == 'exit':
            print("Exiting cluster management.")
            break
        elif choice == '1':
            old_name = input("Enter the current cluster name: ").strip()
            new_name = input("Enter the new cluster name: ").strip()
            result = processor.change_cluster_name(entity_name, old_name, new_name)
            print(result)
        elif choice == '2':
            values_to_swap = []
            while True:
                value = input("Enter a value to swap (enter 0 when done): ").strip()
                if value == '0':
                    break
                values_to_swap.append(value)

            if not values_to_swap:
                print("No values entered to swap.")
                continue

            old_cluster = input("Enter the cluster name containing the value(s): ").strip()
            new_cluster = input("Enter the target cluster name: ").strip()
            result = processor.swap_value_cluster(entity_name, values_to_swap, old_cluster, new_cluster)
            print(result)
        elif choice == '3':
            first_cluster = input("Enter the name of the first cluster to merge: ").strip()
            second_clusters_to_merge = []
            while True:
                cluster_to_merge = input("Enter a cluster name to merge into the first cluster (enter 0 when done): ").strip()
                if cluster_to_merge == '0':
                    break
                second_clusters_to_merge.append(cluster_to_merge)

            if not second_clusters_to_merge:
                print("No clusters entered to merge.")
                continue

            result = processor.merge_cluster(entity_name, first_cluster, second_clusters_to_merge)
            print(result)
        elif choice == '4':
            cluster_name = input("Enter the name for the new cluster: ").strip()
            result = processor.create_cluster(entity_name, cluster_name)
            print(result)
        else:
            print("Invalid choice. Please enter a number between 1 and 4, or 'exit'.")

