class DictListProcessor:
    """
    A class to process a list of dictionaries with the same keys.
    """
    def __init__(self, data):
        """
        Initializes the processor with a list of dictionaries and calculates unique values.

        Args:
            data (list): A list of dictionaries with the same keys.
        """
        if not isinstance(data, list) or not all(isinstance(d, dict) for d in data):
            raise ValueError("Input data must be a list of dictionaries.")
        if len(data) > 0 and not all(d.keys() == data[0].keys() for d in data):
             raise ValueError("All dictionaries in the list must have the same keys.")

        self.data = data
        self._unique_values = {}
        self._entity_embeddings = {}
        self._entity_clusters = {}

        self._find_unique_values()


    def _find_unique_values(self):
        """
        Calculates and stores all unique values for each key in the data.
        This method is intended for internal use within the class.
        """
        if not self.data:
            print("The data list is empty. Cannot find unique values.")
            return

        # Initialize _unique_values with empty sets for each key
        for key in self.data[0].keys():
          if key != 'image_url'and "random_key":
            self._unique_values[key] = set()

        # Iterate through each dictionary and add values to the sets
        for d in self.data:
            for key, value in d.items():
              if key != 'image_url'and "random_key":
                if isinstance(value, list):
                  for v in value:
                    self._unique_values[key].add(v) # Convert list to tuple before adding to set
                else:
                  self._unique_values[key].add(value)

        for key in self._unique_values.keys():
          self._unique_values[key] = list(self._unique_values[key])

    def get_unique_values(self):
        """
        Returns the dictionary containing unique values for each key.

        Returns:
            dict: A dictionary where keys are the original dictionary keys
                  and values are lists of unique values.
        """
        return self._unique_values

    def get_entity_names(self):
        """
        Returns a list of the entity names (keys of the unique values dictionary).

        Returns:
            list: A list of entity names.
        """
        return list(self._unique_values.keys())

    def get_entity_clusters(self, entity_name):
        """
        Returns the dictionary containing clusters for each entity name.

        Returns:
            string: the name of the entity name
            dict: A dictionary where keys are entity names and values are unique values of entity names.
        """
        return self._entity_clusters[entity_name]


    def set_entity_clusters(self, entity_name, dict_):
        """
        Set the dictionary containing clusters for each entity name.

        Args:
            string: the name of the entity name
            dict: A dictionary where keys are entity names and values are unique values of entity names.
        """
        self._entity_clusters[entity_name] = dict_
        # self.get_entity_clusters(entity_name)


    def change_cluster_name(self, entity_name, old_cluster, new_cluster):
        """
        Change the name of a cluster.

        Args:
            string: old name of the cluster.
            string: new name of the cluster.
        """
        if old_cluster not in self._entity_clusters[entity_name].keys():
          return f'No such {old_cluster} cluster existed; No change is made.'
        if new_cluster in self._entity_clusters[entity_name].keys():
          return f'The {new_cluster} cluster already exists; No change is made.'
        self._entity_clusters[entity_name][new_cluster] = self._entity_clusters[entity_name].pop(old_cluster)
        return self.get_entity_clusters(entity_name)

    def swap_value_cluster(self, entity_name, value, old_cluster, new_cluster):
        """
        Put the value of a cluster to another.

        Args:
            string: value to be swapped.
            string: the cluster name containing the value.
            string: the cluster name that the value is going to be part of it.
        """
        if old_cluster not in self._entity_clusters[entity_name].keys():
          return f'No such {old_cluster} cluster existed; No change is made.'
        if new_cluster not in self._entity_clusters[entity_name].keys():
          return f'No such {new_cluster} cluster existed; No change is made.'

        if isinstance(value, list):
          for v in value:
            if v not in self._entity_clusters[entity_name][old_cluster]:
              return f'No such value {v} in {old_cluster} cluster existed; No change is made.'
        else:
          if value not in self._entity_clusters[entity_name][old_cluster]:
            return f'No such value {value} in {old_cluster} cluster existed; No change is made.'

        if isinstance(value, list):
          for v in value:
            self._entity_clusters[entity_name][new_cluster].append(v)
            self._entity_clusters[entity_name][old_cluster].remove(v)

        else:
          self._entity_clusters[entity_name][new_cluster].append(value)
          self._entity_clusters[entity_name][old_cluster].remove(value)

        return self.get_entity_clusters(entity_name)

    def merge_cluster(self, entity_name, first_cluster, second_cluster):
        """
        Merge two clusters with the name of the first cluster.

        Args:
            string: the first cluster name.
            string: the second cluster name.
        """
        if first_cluster not in self._entity_clusters[entity_name].keys():
          return f'No such {first_cluster} cluster existed; No change is made.'
        if isinstance(second_cluster, list):
          for c in second_cluster:
            if c not in self._entity_clusters[entity_name].keys():
              return f'No such {c} cluster existed; No change is made.'
        else:
          if second_cluster not in self._entity_clusters[entity_name].keys():
            return f'No such {second_cluster} cluster existed; No change is made.'

        if isinstance(second_cluster, list):
          for c in second_cluster:
            self._entity_clusters[entity_name][first_cluster].extend(self._entity_clusters[entity_name][c])
            self._entity_clusters[entity_name].pop(c)

        else:
          self._entity_clusters[entity_name][first_cluster].extend(self._entity_clusters[entity_name][second_cluster])
          self._entity_clusters[entity_name].pop(second_cluster)

        return self.get_entity_clusters(entity_name)

    def create_cluster(self, entity_name, cluster_name):
        """
        Create a new cluster

        Args:
            string: the new cluster name.
        """
        if cluster_name in self._entity_clusters[entity_name].keys():
          return f'The {cluster_name} cluster already exists; No change is made.'

        self._entity_clusters[entity_name][cluster_name] = []
        return self.get_entity_clusters(entity_name)

